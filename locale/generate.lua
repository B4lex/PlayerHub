-- Generates the English text catalog and Text::Id from the gettext template beside
-- this script, and checks every translation the way the plugin does when it loads
-- them. The locale rule in xmake.lua runs it before every build. To check the files
-- without building, run `xmake l locale/generate.lua [outdir]`.

local kTemplate = "playerhub.pot"
-- Text.cpp keeps a form per plural rule index in a fixed array.
local kMaximumPluralForms = 6
-- Text.cpp's limit on fields per text.
local kMaximumFields = 8
local kOutputDir = "text/locale"
-- A translation's file name, which [UI] Language stores; Text.cpp checks the same.
local kCodePattern = "^%a[%w_@-]*$"
local kEnglishCode = "en"
local kMaximumCodeLength = 32
local kGenerated = "// Generated by locale/generate.lua from %s. Do not edit.\n"

local kEscapes = { n = "\n", t = "\t", r = "\r", ["\\"] = "\\", ['"'] = '"' }

local function _unquote(text, where)
    if #text < 2 or text:sub(1, 1) ~= '"' or text:sub(-1) ~= '"' then
        raise("%s: expected a quoted string", where)
    end
    local body = text:sub(2, -2)
    local parts = {}
    local i = 1
    while i <= #body do
        local special = body:find('[\\"]', i)
        if not special then
            table.insert(parts, body:sub(i))
            break
        end
        table.insert(parts, body:sub(i, special - 1))
        if body:sub(special, special) == '"' then
            raise("%s: unescaped quote", where)
        end
        local escaped = kEscapes[body:sub(special + 1, special + 1)]
        if not escaped then
            raise("%s: unsupported escape", where)
        end
        table.insert(parts, escaped)
        i = special + 2
    end
    return table.concat(parts)
end

local function _parse_po(file)
    local messages = {}
    local current
    -- The string a continuation line appends to: "msgctxt", "msgid", "msgid_plural", or a msgstr index.
    local target

    local function finish()
        if current and current.msgid then
            table.insert(messages, current)
        elseif current and (current.context or next(current.forms)) then
            raise("%s:%d: entry has no msgid", file, current.line)
        end
        current = nil
        target = nil
    end

    local function start(number)
        if current and current.msgid then
            finish()
        end
        current = current or { line = number, forms = {}, flags = {}, comments = {} }
    end

    local number = 0
    for raw in (io.readfile(file) .. "\n"):gmatch("(.-)\r?\n") do
        number = number + 1
        local where = string.format("%s:%d", file, number)
        local line = raw:trim()
        if line == "" or line:startswith("#~") then
            -- A blank line ends an entry; #~ marks an obsolete one msgmerge keeps for reference.
            finish()
        elseif line:startswith("#") then
            start(number)
            if line:startswith("#,") then
                for flag in line:sub(3):gmatch("[^,%s]+") do
                    current.flags[flag] = true
                end
            elseif line:startswith("#.") then
                table.insert(current.comments, line:sub(3):trim())
            end
        elseif line:startswith('"') then
            if not target then
                raise("%s: string outside an entry", where)
            end
            local value = _unquote(line, where)
            if type(target) == "number" then
                current.forms[target] = current.forms[target] .. value
            elseif target == "msgctxt" then
                current.context = current.context .. value
            elseif target == "msgid" then
                current.msgid = current.msgid .. value
            else
                current.plural = current.plural .. value
            end
        else
            local keyword, rest = line:match("^(%S+)%s+(.*)$")
            if not keyword then
                raise("%s: cannot read the line", where)
            end
            local value = _unquote(rest, where)
            if keyword == "msgctxt" then
                start(number)
                current.context = value
                target = "msgctxt"
            else
                current = current or { line = number, forms = {}, flags = {}, comments = {} }
                local index = keyword == "msgstr" and 0 or tonumber(keyword:match("^msgstr%[(%d+)%]$"))
                if keyword == "msgid" then
                    if current.msgid then
                        raise("%s: second msgid in one entry", where)
                    end
                    current.msgid = value
                    target = "msgid"
                elseif keyword == "msgid_plural" then
                    current.plural = value
                    target = "msgid_plural"
                elseif index then
                    if current.forms[index] then
                        raise("%s: %s given twice", where, keyword)
                    end
                    current.forms[index] = value
                    target = index
                else
                    raise("%s: unknown keyword %s", where, keyword)
                end
            end
        end
    end
    finish()

    local headers = {}
    if messages[1] and messages[1].msgid == "" and not messages[1].context then
        for header in (table.remove(messages, 1).forms[0] or ""):gmatch("[^\n]+") do
            local name, value = header:match("^([^:]+):(.*)$")
            if name then
                headers[name:trim()] = value:trim()
            end
        end
    end
    return { file = file, headers = headers, messages = messages }
end

-- Plural-Forms expressions are C; the same text becomes the catalog's C++ rule.
local kBinary = {
    ["||"] = { 1, function (a, b) return (a ~= 0 or b ~= 0) and 1 or 0 end },
    ["&&"] = { 2, function (a, b) return (a ~= 0 and b ~= 0) and 1 or 0 end },
    ["=="] = { 3, function (a, b) return a == b and 1 or 0 end },
    ["!="] = { 3, function (a, b) return a ~= b and 1 or 0 end },
    ["<"] = { 4, function (a, b) return a < b and 1 or 0 end },
    [">"] = { 4, function (a, b) return a > b and 1 or 0 end },
    ["<="] = { 4, function (a, b) return a <= b and 1 or 0 end },
    [">="] = { 4, function (a, b) return a >= b and 1 or 0 end },
    ["+"] = { 5, function (a, b) return a + b end },
    ["-"] = { 5, function (a, b) return a - b end },
    ["*"] = { 6, function (a, b) return a * b end },
    ["/"] = { 6, function (a, b) return b ~= 0 and math.floor(a / b) or nil end },
    ["%"] = { 6, function (a, b) return b ~= 0 and math.fmod(a, b) or nil end },
}

local function _compile_plural(expression, where)
    local tokens = {}
    local position = 1
    while true do
        position = expression:find("%S", position)
        if not position then
            break
        end
        local token = expression:match("^%d+", position) or expression:match("^n", position)
            or expression:match("^[|&=!<>]=?", position) or expression:match("^[-+*/%%?:()]", position)
        if token == "|" or token == "&" or token == "=" then
            token = expression:match("^||", position) or expression:match("^&&", position)
        end
        if not token then
            raise("%s: cannot read the plural expression at '%s'", where, expression:sub(position))
        end
        table.insert(tokens, token)
        position = position + #token
    end
    local index = 1

    local function take(expected)
        local token = tokens[index]
        if expected and token ~= expected then
            raise("%s: expected '%s' in the plural expression", where, expected)
        end
        index = index + 1
        return token
    end

    local ternary
    local function primary()
        local token = take()
        if token == "(" then
            local inner = ternary()
            take(")")
            return inner
        elseif token == "!" then
            local operand = primary()
            return function (n)
                local value = operand(n)
                if value == nil then
                    return nil
                end
                return value == 0 and 1 or 0
            end
        elseif token == "n" then
            return function (n) return n end
        elseif token and token:match("^%d+$") then
            local value = tonumber(token)
            return function () return value end
        end
        raise("%s: unexpected '%s' in the plural expression", where, tostring(token))
    end

    local function binary(minimum)
        local left = primary()
        while kBinary[tokens[index]] and kBinary[tokens[index]][1] >= minimum do
            local operator = kBinary[take()]
            local operation = operator[2]
            local right = binary(operator[1] + 1)
            local l = left
            left = function (n)
                local a, b = l(n), right(n)
                -- nil is a division by zero, which every later operation passes on.
                if a == nil or b == nil then
                    return nil
                end
                return operation(a, b)
            end
        end
        return left
    end

    ternary = function ()
        local condition = binary(1)
        if tokens[index] ~= "?" then
            return condition
        end
        take("?")
        local yes = ternary()
        take(":")
        local no = ternary()
        return function (n)
            local value = condition(n)
            if value == nil then
                return nil
            elseif value ~= 0 then
                return yes(n)
            end
            return no(n)
        end
    end

    local rule = ternary()
    if tokens[index] then
        raise("%s: unexpected '%s' in the plural expression", where, tokens[index])
    end
    return rule
end

local function _read_plural_forms(catalog)
    local where = catalog.file .. ": Plural-Forms"
    local value = catalog.headers["Plural-Forms"]
    if not value then
        raise("%s: header has no Plural-Forms", catalog.file)
    end
    local count, expression = value:match("^nplurals%s*=%s*(%d+)%s*;%s*plural%s*=%s*(.-)%s*;?$")
    if not count then
        raise("%s: expected 'nplurals=N; plural=EXPRESSION;'", where)
    end
    count = tonumber(count)
    if count < 1 or count > kMaximumPluralForms then
        raise("%s: nplurals must be 1 to %d", where, kMaximumPluralForms)
    end
    expression = expression:gsub("%s+", " ")
    local rule = _compile_plural(expression, where)
    for n = 0, 9999 do
        local form = rule(n)
        if form == nil then
            raise("%s: divides by zero for n = %d", where, n)
        elseif form < 0 or form >= count then
            raise("%s: gives form %s for n = %d, but nplurals is %d", where, tostring(form), n, count)
        end
    end
    return { count = count, expression = expression }
end

-- The fields of a std::format string as "index:spec" keys, or nil where Text.cpp's Scan rejects it.
local function _parse_fields(text)
    local fields = {}
    local following = 0
    local automatic, manual = false, false
    local i = 1
    while true do
        i = text:find("[{}]", i)
        if not i then
            break
        end
        local character = text:sub(i, i)
        if text:sub(i + 1, i + 1) == character then
            i = i + 2
        else
            if character == "}" then
                return nil
            end
            local close = text:find("}", i + 1, true)
            if not close then
                return nil
            end
            local content = text:sub(i + 1, close - 1)
            if content:find("{", 1, true) then
                return nil
            end
            local indexText, spec = content:match("^([^:]*)(.*)$")
            local index
            if indexText ~= "" then
                if not indexText:match("^%d%d?%d?$") then
                    return nil
                end
                manual = true
                index = tonumber(indexText)
            else
                automatic = true
                index = following
                following = following + 1
            end
            if automatic and manual then
                return nil
            end
            table.insert(fields, { index = index, key = index .. spec, text = "{" .. content .. "}" })
            i = close + 1
        end
    end
    if #fields > kMaximumFields then
        return nil
    end
    return fields
end

local function _read_template(localedir)
    local file = path.join(localedir, kTemplate)
    local catalog = _parse_po(file)
    local plural = _read_plural_forms(catalog)
    if plural.count ~= 2 then
        raise("%s: English has two plural forms", file)
    end
    local sources = {}
    local keys = {}
    for _, message in ipairs(catalog.messages) do
        local where = string.format("%s:%d", file, message.line)
        local key = message.context
        if not key or not key:match("^[A-Z][A-Za-z0-9]*$") then
            raise("%s: msgctxt must name a Text::Id without its k prefix", where)
        end
        if keys[key] then
            raise("%s: %s is listed twice", where, key)
        end
        keys[key] = true
        local forms = { message.msgid, message.plural }
        local fields = {}
        local hasFields = false
        for _, form in ipairs(forms) do
            if form == "" then
                raise("%s: %s has no English text", where, key)
            end
            local parsed = _parse_fields(form)
            if not parsed then
                raise("%s: %s is not a valid format", where, key)
            end
            for _, f in ipairs(parsed) do
                fields[f.key] = f.index
                hasFields = true
            end
        end
        if hasFields and not message.flags["c++-format"] then
            raise("%s: %s has fields, so it needs '#, c++-format' for msgfmt -c", where, key)
        end
        for _, value in pairs(message.forms) do
            if value ~= "" then
                raise("%s: %s has a msgstr; the template holds English in msgid only", where, key)
            end
        end
        table.insert(sources, { key = key, forms = forms, fields = fields })
    end
    return catalog.headers["Plural-Forms"], sources
end

local function _check_translation(source, text, usesAll)
    local fields = _parse_fields(text)
    if not fields then
        return "is not a valid format"
    end
    local used = {}
    for _, f in ipairs(fields) do
        if not source.fields[f.key] then
            return "uses a field the English text does not have: " .. f.text
        end
        used[f.index] = true
    end
    if usesAll then
        for _, index in pairs(source.fields) do
            if not used[index] then
                return "leaves out argument " .. index
            end
        end
    end
end

local function _read_translation(localedir, code, sources, errors)
    local file = path.join(localedir, code .. ".po")
    local catalog = _parse_po(file)
    local plural = _read_plural_forms(catalog)
    if catalog.headers["Language"] ~= code then
        raise("%s: Language header is '%s', expected '%s'", file, tostring(catalog.headers["Language"]), code)
    end
    local gameLanguage = catalog.headers["X-Skyrim-Language"]
    if gameLanguage and not gameLanguage:match("^[A-Z]+$") then
        raise("%s: X-Skyrim-Language must be an sLanguage value in capitals, such as FRENCH", file)
    end
    local byKey = {}
    for _, source in ipairs(sources) do
        byKey[source.key] = source
    end
    local translations = {}
    for _, message in ipairs(catalog.messages) do
        local where = string.format("%s:%d", file, message.line)
        local key = message.context
        local source = key and byKey[key]
        local function fail(format, ...)
            table.insert(errors, string.format("%s: %s ", where, tostring(key)) .. string.format(format, ...))
        end
        if not source then
            fail("is not in %s", kTemplate)
        elseif translations[key] then
            fail("is listed twice")
        elseif message.msgid ~= source.forms[1] or message.plural ~= source.forms[2] then
            fail("translates an older English text; update it from %s", kTemplate)
        elseif message.flags["fuzzy"] then
            fail("is marked fuzzy; review it and remove the flag")
        else
            local isPlural = source.forms[2] ~= nil
            local expected = isPlural and plural.count or 1
            local count = expected
            for index in pairs(message.forms) do
                count = math.max(count, index + 1)
            end
            local forms = {}
            local filled = 0
            for index = 0, count - 1 do
                forms[index + 1] = message.forms[index] or ""
                filled = filled + (forms[index + 1] ~= "" and 1 or 0)
            end
            if filled > 0 then
                if count ~= expected or filled ~= count then
                    fail("needs %d translated form(s)", expected)
                else
                    local problem
                    for _, form in ipairs(forms) do
                        problem = problem or _check_translation(source, form, not isPlural)
                    end
                    if problem then
                        fail("%s", problem)
                    else
                        translations[key] = true
                    end
                end
            end
        end
    end
    return translations
end

local function _cpp_string(text)
    return '"' .. text:gsub('[%c\\"]', function (character)
        if character == "\n" then
            return "\\n"
        elseif character == "\t" then
            return "\\t"
        elseif character == "\\" or character == '"' then
            return "\\" .. character
        end
        return string.format("\\%03o", character:byte())
    end) .. '"'
end

local function _render_ids(sources)
    local lines = {
        string.format(kGenerated, "locale/" .. kTemplate),
        "#pragma once\n\n#include <cstdint>\n\nnamespace Text\n{\n    enum class Id : std::uint16_t\n    {\n",
        "        kNone,\n",
    }
    for _, source in ipairs(sources) do
        table.insert(lines, "        k" .. source.key .. ",\n")
    end
    table.insert(lines, "        kCount\n    };\n}\n")
    return table.concat(lines)
end

local function _render_english(pluralForms, sources)
    local lines = {
        string.format(kGenerated, "locale/" .. kTemplate),
        '#include "text/locale/English.h"\n\n#include <array>\n\n',
        "namespace Text::Catalogs\n{\n    namespace\n    {\n",
        string.format("        constexpr std::array<Entry, %d> kEntries{\n", #sources),
    }
    for _, source in ipairs(sources) do
        table.insert(lines, string.format("            Entry{ Id::k%s, %s, %s, %s },\n", source.key,
            _cpp_string(source.key), _cpp_string(source.forms[1]), _cpp_string(source.forms[2] or "")))
    end
    table.insert(lines, "        };\n    }\n\n")
    table.insert(lines, "    English GetEnglish()\n    {\n")
    table.insert(lines, string.format("        return English{ kEntries, %s };\n", _cpp_string(pluralForms)))
    table.insert(lines, "    }\n}\n")
    return table.concat(lines)
end

local kEnglishHeader = [==[
#pragma once

#include "text/locale/TextId.h"

#include <cstddef>
#include <span>
#include <string_view>

namespace Text::Catalogs
{
    inline constexpr std::size_t kMaximumPluralForms = %d;

    struct Entry
    {
        Id id;
        // The msgctxt that names the Id in the gettext files.
        std::string_view key;
        std::string_view text;
        // Empty unless the text has plural forms.
        std::string_view plural;
    };

    struct English
    {
        std::span<const Entry> entries;
        // The template's Plural-Forms header.
        std::string_view pluralForms;
    };

    [[nodiscard]] English GetEnglish();
}
]==]

-- The generated sources the target compiles, relative to the output directory.
function sources()
    return { path.join(kOutputDir, "English.cpp") }
end

-- Validates the gettext files and, given outdir, writes the files that changed.
-- Returns the paths written and a line per translation with its translated count.
function run(outdir)
    local localedir = os.scriptdir()
    local pluralForms, sources = _read_template(localedir)
    local files = {
        ["TextId.h"] = _render_ids(sources),
        ["English.h"] = string.format(kGenerated, "locale/generate.lua") .. string.format(kEnglishHeader,
            kMaximumPluralForms),
        ["English.cpp"] = _render_english(pluralForms, sources),
    }

    local errors = {}
    local summary = {}
    local translations = os.files(path.join(localedir, "*.po"))
    table.sort(translations)
    for _, file in ipairs(translations) do
        local code = path.basename(file)
        if #code > kMaximumCodeLength or not code:match(kCodePattern) or code:lower() == kEnglishCode then
            raise("%s: the file name must be a language code other than %s, such as de or zh_TW", file, kEnglishCode)
        end
        local translated = _read_translation(localedir, code, sources, errors)
        local count = 0
        for _ in pairs(translated) do
            count = count + 1
        end
        table.insert(summary, { code = code, translated = count, total = #sources })
    end
    if #errors > 0 then
        raise("%s", table.concat(errors, "\n"))
    end

    local written = {}
    if outdir then
        for name, content in pairs(files) do
            local file = path.join(outdir, kOutputDir, name)
            if not os.isfile(file) or io.readfile(file) ~= content then
                io.writefile(file, content)
                table.insert(written, file)
            end
        end
    end
    return written, summary
end

function main(outdir)
    local written, summary = run(outdir and path.absolute(outdir))
    for _, line in ipairs(summary) do
        print("%s: %d of %d translated", line.code, line.translated, line.total)
    end
    for _, file in ipairs(written) do
        print("wrote %s", file)
    end
end
